# Writes gemset-platforms.nix: the version and hash of every platform variant of
# each gem that Gemfile.lock lists with a precompiled platform. bundix keeps one
# hash per gem, so flake.nix reads this file to fetch the right variant per system.
#
# Run by scripts/generate_nix_gemfile_lock_and_gemset.sh.

require "bundler"

def sha256(file)
  url = "https://rubygems.org/gems/#{file}.gem"
  hash = `nix-prefetch-url --type sha256 #{url} 2>/dev/null`.strip
  abort "nix-prefetch-url failed for #{url}" unless $?.success? && !hash.empty?
  hash
end

lockfile = Bundler::LockfileParser.new(File.read("Gemfile.lock"))
gems = lockfile.specs
  .group_by(&:name)
  .select { |_, specs| specs.any? { |spec| spec.platform.to_s != "ruby" } }
  .sort

nix = +"# Generated by scripts/generate_nix_gemfile_lock_and_gemset.sh. Do not edit.\n{\n"
gems.each do |name, specs|
  nix << "  \"#{name}\" = {\n"
  specs.sort_by { |spec| spec.platform.to_s }.each do |spec|
    puts "Fetching #{spec.full_name}"
    nix << "    \"#{spec.platform}\" = {\n"
    nix << "      version = \"#{spec.full_name.delete_prefix("#{name}-")}\";\n"
    nix << "      sha256 = \"#{sha256(spec.full_name)}\";\n"
    nix << "    };\n"
  end
  nix << "  };\n"
end
nix << "}\n"

File.write("gemset-platforms.nix", nix)
